-- 同一试剂下的批次号唯一。
--
-- 在这之前只靠应用层查重：把该试剂的全部批次读进内存再逐条比对批次号。
-- 这带来两个问题，压测时都暴露了：
--   1. O(n)。同一试剂批次过千后，入库吞吐随批次数增长线性下降
--      （10 批次约 377 QPS，7900 批次约 114 QPS，换一个新试剂立刻回到 344 QPS）。
--   2. 「先查后插」之间有窗口，两个并发请求可以都通过检查，插出两条同号批次。
--
-- 唯一索引让数据库同时解决这两件事：查重变成索引点查，冲突由约束兜底。
-- CREATE UNIQUE INDEX 在 H2 2.x 与 MySQL 8 上写法一致，不需要分支。
--
-- 存量数据若已有重复批次号，本迁移会失败。这是有意为之：重复批次意味着
-- 台账上同一瓶试剂被记了两次，属于需要人工确认的数据问题，
-- 不能被「先删掉一条」之类的自动化脚本掩盖。
CREATE UNIQUE INDEX uk_batch_chemical_no ON chemical_batch (chemical_id, batch_no);
